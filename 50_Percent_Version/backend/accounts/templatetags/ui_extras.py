@register.simple_tag
def icon(name, size=20):
    """{% icon 'users' %} -> inline SVG"""
    inner = ICONS.get(name, "")
    return format_html(
        '<svg class="icon" width="{0}" height="{0}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{1}</svg>',
        size,
        mark_safe(inner),
    )


@register.filter
def progress_color(value):
    """Progress % onujayi color class."""
    try:
        value = int(value)
    except (TypeError, ValueError):
        return "low"
    if value >= 80:
        return "high"
    if value >= 40:
        return "mid"
    return "low"


@register.filter
def level_label(value):
    labels = {0: "Not assessed", 1: "Beginner", 2: "Basic", 3: "Intermediate", 4: "Advanced", 5: "Expert"}
    try:
        return labels.get(int(value), "-")
    except (TypeError, ValueError):
        return "-"
